<script>
  (function () {
    var mql992 = window.matchMedia('(max-width: 992px)');
    var mql1280 = window.matchMedia('(min-width: 1280px)');

    function getSlidesPerView() {
      if (mql992.matches) return 1.08;
      if (mql1280.matches) return 2.15;
      return 1.6;
    }
    function getSpaceBetween() {
      if (mql992.matches) return 14;
      if (mql1280.matches) return 30;
      return 14;
    }
    function getCardHeight() {
      if (mql992.matches) return 320;
      if (mql1280.matches) return 590;
      return 330;
    }

    function setCardHeights(h) {
      var cards = document.querySelectorAll('#ddokReviewSwiper .ddok-card, #ddokReviewSwiper .ddok-last-card');
      cards.forEach(function(c) { c.style.height = h + 'px'; });
      var inners = document.querySelectorAll('#ddokReviewSwiper .ddok-card-inner');
      inners.forEach(function(el) { el.style.maxHeight = (h - 220) + 'px'; });
    }

    var swiper = new Swiper('#ddokReviewSwiper', {
      slidesPerView: getSlidesPerView(),
      spaceBetween: getSpaceBetween(),
      loop: false,
      pagination: {
        el: '#ddokReviewSwiper .swiper-pagination',
        clickable: true,
      },
      on: {
        init: function() { setCardHeights(getCardHeight()); }
      }
    });

    function onResize() {
      swiper.params.slidesPerView = getSlidesPerView();
      swiper.params.spaceBetween = getSpaceBetween();
      swiper.update();
      setCardHeights(getCardHeight());
    }
    window.addEventListener('resize', onResize);
  })();
</script>